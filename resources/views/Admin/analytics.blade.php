document.addEventListener("DOMContentLoaded", function() {
    // Pie Chart Data
    const payslipData = @json($payslipTypes);
    const labels = Object.keys(payslipData).length ? Object.keys(payslipData).map(k => k.toUpperCase()) : ['USA', 'UK', 'CANADA', 'GLOBAL'];
    const values = Object.keys(payslipData).length ? Object.values(payslipData) : [12, 5, 8, 15];

    new Chart(document.getElementById('payslipPieChart'), {
        type: 'doughnut',
        data: {
            labels: labels,
            datasets: [{
                data: values,
                backgroundColor: ['#6366f1', '#10b981', '#f59e0b', '#ec4899'],
                borderWidth: 0
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            plugins: {
                legend: {
                    position: 'bottom',
                    labels: { color: '#9ca3af', font: { family: 'Outfit', size: 13 } }
                }
            }
        }
    });

    // Bar Chart Data
    new Chart(document.getElementById('userGrowthChart'), {
        type: 'bar',
        data: {
            labels: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
